        <?php
        // Show error message if there is one
        if (!empty($error_message)) {
            echo '<div class="auth-error">' . htmlspecialchars($error_message) . '</div>';
        }
        ?>

        <div class="auth-tabs">
            <div class="auth-tab active" id="tab-customer">CUSTOMER</div>
            <div class="auth-tab" id="tab-trader">TRADER</div>
        </div>

        <!-- The form submits to register.php (this same page) -->
        <form action="register.php" method="POST" id="register-form">
            <!-- Hidden field updated by JavaScript when tab is clicked -->
            <input type="hidden" name="role" id="role-input" value="customer">

            <div class="auth-form-group">
                <div class="auth-label">FULL NAME</div>
                <!-- name="name" matches $_POST['name'] in the PHP above -->
                <input type="text" class="auth-input" name="name" required
                       value="<?php echo isset($_POST['name']) ? htmlspecialchars($_POST['name']) : ''; ?>">
            </div>

            <div class="auth-form-group">
                <div class="auth-label">EMAIL ADDRESS</div>
                <input type="email" class="auth-input" name="email" required
                       value="<?php echo isset($_POST['email']) ? htmlspecialchars($_POST['email']) : ''; ?>">
            </div>

            <div class="auth-form-group">
                <div class="auth-label">PASSWORD</div>
                <input type="password" class="auth-input" name="password" required>
            </div>

            <div class="auth-form-group">
                <div class="auth-label">HOME ADDRESS</div>
                <textarea class="auth-input" name="address" required><?php echo isset($_POST['address']) ? htmlspecialchars($_POST['address']) : ''; ?></textarea>
            </div>

